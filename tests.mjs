import assert from 'node:assert/strict';
import { CALCULATORS, CATEGORY_META, computeTool, convertUnit, evaluateExpression } from './calculators.mjs';
const near = (a,b,eps=1e-6)=> assert.ok(Math.abs(a-b)<=eps,`Expected ${a} ≈ ${b}`);
assert.equal(CALCULATORS.length,30);
assert.equal(new Set(CALCULATORS.map(t=>t.id)).size,CALCULATORS.length,'Tool IDs must be unique');
assert.ok(!CALCULATORS.some(tool=>tool.id==='nup'),'N-up layout must be removed');
for(const tool of CALCULATORS){
  assert.ok(CATEGORY_META[tool.category],`Missing category for ${tool.id}`);
  assert.ok(tool.title && tool.summary && tool.icon,`Missing UI data for ${tool.id}`);
  if(['basic','scientific','currency'].includes(tool.id))continue;
  const defaults=Object.fromEntries(tool.fields.map(f=>[f.id,f.type==='number'?Number(f.value):f.value]));
  const result=computeTool(tool.id,defaults);
  assert.ok(result.label && result.format,`Missing result for ${tool.id}`);
  if(typeof result.value==='number')assert.ok(Number.isFinite(result.value),`Non-finite default for ${tool.id}`);
}
near(computeTool('dp',{invoice:2500000,percent:60}).value,1500000);
near(computeTool('discount',{price:200000,discount:25}).value,150000);
near(computeTool('selling',{cost:100000,method:'markup',percent:30}).value,130000);
near(computeTool('selling',{cost:100000,method:'margin',percent:30}).value,100000/.7);
near(computeTool('margin',{cost:70,price:100}).value,30);
near(computeTool('tax',{price:111000,rate:11,mode:'inclusive'}).extra[1].value,11000);
near(computeTool('loan',{principal:12000,annual:0,months:12}).value,1000);
near(computeTool('bep',{fixed:2000000,price:25000,variable:15000}).value,200);
near(computeTool('unit',{kind:'Suhu',from:'°C',to:'°F',amount:100}).value,212);
near(convertUnit('Berat','kg','g',2),2000);
near(convertUnit('Suhu','°F','°C',32),0);
near(computeTool('print-area',{width:300,height:100,qty:1,price:25000}).value,75000);
near(evaluateExpression('2+3*4'),14);
near(evaluateExpression('(2+3)*4'),20);
near(evaluateExpression('sin(30)+sqrt(9)',true),3.5);
near(evaluateExpression('-2^2',true),-4);
near(evaluateExpression('2^-3',true),.125);
near(evaluateExpression('5!',true),120);
near(evaluateExpression('50%',false),.5);
assert.throws(()=>evaluateExpression('1/0'),/nol/);
assert.throws(()=>evaluateExpression('alert(1)',true));
assert.throws(()=>computeTool('selling',{cost:100000,method:'margin',percent:100}),/100/);
assert.throws(()=>convertUnit('Suhu','K','°C',-1),/nol absolut/);
console.log('Kalkulin: 30 default calculators + numerical and edge-case checks PASSED');
